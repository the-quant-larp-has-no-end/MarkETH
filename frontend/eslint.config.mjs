import { defineConfig, globalIgnores } from "eslint/config";
import nextVitals from "eslint-config-next/core-web-vitals";
import nextTs from "eslint-config-next/typescript";
import prettier from "eslint-plugin-prettier/recommended";

// Field names that carry an amount: the API sends them as decimal strings and the
// frontend shows them as sent (CLAUDE.md, golden rule 6).
const AMOUNT = "/(_cr|^shares|^min_shares)$/";
const AMOUNT_TO_NUMBER = "Never turn a *_cr or shares value into a number.";

const STORAGE =
  "The app keeps nothing in the browser: a code, a voucher code and an unanswered trade live in memory (DESIGN §13, §14).";

/* What may import what. A later entry replaces an earlier one for the files it names. */
const NEXT_LINK = {
  name: "next/link",
  message:
    "Use Link from @/components/shell: the same link, and it drives the route progress line.",
};
const FEATURE_INTERNALS = {
  group: ["@/features/*/*"],
  message: "Import a feature through its index.",
};
const imports = (patterns, { nextLink = false } = {}) => [
  "error",
  { paths: nextLink ? [] : [NEXT_LINK], patterns },
];

const GLOBALS = [
  { name: "parseFloat", message: "Amounts are strings (DESIGN §10)." },
  {
    name: "fetch",
    message: "Only lib/api/client.ts talks to the network: use call() from @/lib/api/client.",
  },
  { name: "localStorage", message: STORAGE },
  { name: "sessionStorage", message: STORAGE },
  { name: "indexedDB", message: STORAGE },
];
const STORAGE_PROPERTIES = ["localStorage", "sessionStorage", "indexedDB"].flatMap((property) => [
  { object: "window", property, message: STORAGE },
  { object: "globalThis", property, message: STORAGE },
]);

export default defineConfig([
  ...nextVitals,
  ...nextTs,
  globalIgnores([
    ".next/**",
    "out/**",
    "coverage/**",
    "test-results/**",
    "playwright-report/**",
    "next-env.d.ts",
    // Generated by `npm run generate:api`; never edited or reformatted.
    "src/lib/api/schema.d.ts",
  ]),
  {
    files: ["src/**/*.{ts,tsx}"],
    rules: {
      "no-restricted-globals": ["error", ...GLOBALS],
      "no-restricted-properties": ["error", ...STORAGE_PROPERTIES],
      "no-restricted-syntax": [
        "error",
        {
          selector: `CallExpression[callee.name='Number'] > MemberExpression.arguments[property.name=${AMOUNT}]`,
          message: AMOUNT_TO_NUMBER,
        },
        {
          selector: `UnaryExpression[operator='+'] > MemberExpression[property.name=${AMOUNT}]`,
          message: AMOUNT_TO_NUMBER,
        },
        {
          selector: `BinaryExpression[operator=/^(<|>|<=|>=|-|\\*|\\/)$/] > MemberExpression[property.name=${AMOUNT}]`,
          message:
            "Never compare or calculate with a *_cr or shares value; the API sends the answer.",
        },
        {
          selector: "MemberExpression[object.name='process'][property.name='env']",
          message: "The frontend reads no environment (SPEC A.11).",
        },
      ],
      "no-restricted-imports": imports([FEATURE_INTERNALS]),
      // A name that starts with an underscore says "not used, on purpose": a callback
      // parameter that only holds a place, a field taken out of an object to drop it.
      "@typescript-eslint/no-unused-vars": [
        "warn",
        {
          argsIgnorePattern: "^_",
          varsIgnorePattern: "^_",
          caughtErrorsIgnorePattern: "^_",
          destructuredArrayIgnorePattern: "^_",
          ignoreRestSiblings: true,
        },
      ],
    },
  },
  // Layers: imports only point downwards. lib knows nothing above it; components know
  // lib; a feature knows both and other features through their index; app knows features.
  {
    files: ["src/lib/**"],
    rules: {
      "no-restricted-imports": imports([
        {
          group: ["@/components/*", "@/features/*", "@/app/*"],
          message: "lib imports nothing from the layers above it.",
        },
      ]),
    },
  },
  {
    files: ["src/components/**"],
    rules: {
      "no-restricted-imports": imports([
        { group: ["@/features/*", "@/app/*"], message: "A shared component knows no feature." },
      ]),
    },
  },
  {
    files: ["src/features/**"],
    rules: {
      "no-restricted-imports": imports([
        FEATURE_INTERNALS,
        { group: ["@/app/*"], message: "A feature knows nothing of the routes that show it." },
      ]),
    },
  },
  // The two places that are the exception they describe.
  {
    files: ["src/components/shell/link.tsx"],
    rules: {
      "no-restricted-imports": imports(
        [{ group: ["@/features/*", "@/app/*"], message: "A shared component knows no feature." }],
        { nextLink: true },
      ),
    },
  },
  {
    files: ["src/lib/session-recovery.ts"],
    rules: { "no-restricted-properties": "off" },
  },
  // Tests look at what the app must not touch.
  {
    files: ["src/test/**", "src/**/*.test.{ts,tsx}"],
    rules: {
      "no-restricted-globals": [
        "error",
        { name: "parseFloat", message: "Amounts are strings (DESIGN §10)." },
      ],
      "no-restricted-properties": "off",
    },
  },
  prettier,
]);
